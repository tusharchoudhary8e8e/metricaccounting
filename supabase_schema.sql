-- 1. Create Tenants Table
CREATE TABLE IF NOT EXISTS public.tenants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL DEFAULT 'Default Tenant',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Insert Default Tenant (ID: 1) if not existing
INSERT INTO public.tenants (id, name)
VALUES (1, 'Default Tenant')
ON CONFLICT (id) DO NOTHING;

-- 2. Create Companies Table (Stores Company Info & Master Settings)
CREATE TABLE IF NOT EXISTS public.companies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    financial_year TEXT NOT NULL,
    books_from TEXT NOT NULL,
    state TEXT,
    gstin TEXT,
    tenant_id BIGINT NOT NULL DEFAULT 1 REFERENCES public.tenants(id) ON DELETE CASCADE,
    user_id TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. Create Ledgers Table (Chart of Accounts Master)
CREATE TABLE IF NOT EXISTS public.ledgers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    group_name TEXT NOT NULL,
    opening NUMERIC NOT NULL DEFAULT 0,
    is_system BOOLEAN NOT NULL DEFAULT FALSE,
    tenant_id BIGINT NOT NULL DEFAULT 1 REFERENCES public.tenants(id) ON DELETE CASCADE,
    user_id TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 4. Create Parties Table (Sundry Debtors & Creditors Master)
CREATE TABLE IF NOT EXISTS public.parties (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    group_name TEXT NOT NULL,
    address TEXT NOT NULL DEFAULT '',
    phone TEXT NOT NULL DEFAULT '',
    gstin TEXT NOT NULL DEFAULT '',
    state TEXT,
    opening TEXT NOT NULL DEFAULT '0',
    tenant_id BIGINT NOT NULL DEFAULT 1 REFERENCES public.tenants(id) ON DELETE CASCADE,
    user_id TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 5. Create Stock Items Table (Inventory Items Master)
CREATE TABLE IF NOT EXISTS public.stock_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    alias TEXT,
    group_name TEXT NOT NULL,
    unit TEXT NOT NULL,
    opening_qty NUMERIC NOT NULL DEFAULT 0,
    opening_rate NUMERIC NOT NULL DEFAULT 0,
    opening_value NUMERIC NOT NULL DEFAULT 0,
    valuation_method TEXT DEFAULT 'FIFO',
    gst_applicability TEXT,
    hsn_details TEXT,
    hsn_code TEXT,
    description TEXT,
    gst_rate_details TEXT,
    gst_rate NUMERIC DEFAULT 0,
    type_of_supply TEXT DEFAULT 'Goods',
    rate_of_duty NUMERIC DEFAULT 0,
    tenant_id BIGINT NOT NULL DEFAULT 1 REFERENCES public.tenants(id) ON DELETE CASCADE,
    user_id TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 6. Create Vouchers Table (Financial Transactions Header)
CREATE TABLE IF NOT EXISTS public.vouchers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vno TEXT NOT NULL,
    date TEXT NOT NULL,
    type TEXT NOT NULL,
    particulars TEXT NOT NULL,
    account TEXT,
    party_id BIGINT REFERENCES public.parties(id) ON DELETE SET NULL,
    ledger_id BIGINT REFERENCES public.ledgers(id) ON DELETE SET NULL,
    item TEXT,
    qty NUMERIC,
    rate NUMERIC,
    advance NUMERIC,
    order_date TEXT,
    delivery_date TEXT,
    amount NUMERIC NOT NULL,
    dr BOOLEAN NOT NULL DEFAULT TRUE,
    narration TEXT,
    taxable_value NUMERIC DEFAULT 0,
    cgst NUMERIC DEFAULT 0,
    sgst NUMERIC DEFAULT 0,
    igst NUMERIC DEFAULT 0,
    total_with_tax NUMERIC DEFAULT 0,
    is_pending_update BOOLEAN DEFAULT FALSE,
    tenant_id BIGINT NOT NULL DEFAULT 1 REFERENCES public.tenants(id) ON DELETE CASCADE,
    user_id TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 7. Create Voucher Line Items Table (Stock item lines per voucher)
CREATE TABLE IF NOT EXISTS public.voucher_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    voucher_id BIGINT NOT NULL REFERENCES public.vouchers(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    qty NUMERIC NOT NULL,
    rate NUMERIC NOT NULL,
    amount NUMERIC NOT NULL,
    gst_rate NUMERIC DEFAULT 0,
    hsn_code TEXT,
    taxable_value NUMERIC DEFAULT 0,
    cgst NUMERIC DEFAULT 0,
    sgst NUMERIC DEFAULT 0,
    igst NUMERIC DEFAULT 0
);

-- 8. Create Voucher Double-Entry Lines Table (Debit/Credit breakdown per voucher)
CREATE TABLE IF NOT EXISTS public.voucher_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    voucher_id BIGINT NOT NULL REFERENCES public.vouchers(id) ON DELETE CASCADE,
    ledger_name TEXT NOT NULL,
    amount NUMERIC NOT NULL,
    dr BOOLEAN NOT NULL
);

-- 9. Create App Settings Table (Stores ALL app settings, Tally connection info, inventory rules, user configs)
CREATE TABLE IF NOT EXISTS public.app_settings (
    key TEXT PRIMARY KEY,
    value JSONB NOT NULL,
    user_id TEXT,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 10. Create Audit Logs Table (Tracks all system changes & Tally XML payloads)
CREATE TABLE IF NOT EXISTS public.audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    timestamp TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    action TEXT NOT NULL,
    details TEXT NOT NULL,
    xml_payload TEXT,
    tenant_id BIGINT NOT NULL DEFAULT 1 REFERENCES public.tenants(id) ON DELETE CASCADE,
    user_id TEXT
);

