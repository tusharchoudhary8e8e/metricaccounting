-- ─── Method 2 Admin Helper: Set/Update Authorized IP for User ───────────────
-- Run this function in Supabase SQL Editor to set or update allowed IP for any account.
-- Example: SELECT public.set_user_allowed_ip('user@domain.com', '203.0.113.19');
CREATE OR REPLACE FUNCTION public.set_user_allowed_ip(target_email text, target_ip text)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_user_id uuid;
BEGIN
  SELECT id INTO v_user_id FROM auth.users WHERE lower(email) = lower(target_email);
  IF v_user_id IS NULL THEN
    RETURN 'Error: User email "' || target_email || '" not found in Supabase Auth.';
  END IF;

  UPDATE auth.users
  SET raw_user_meta_data = jsonb_set(COALESCE(raw_user_meta_data, '{}'::jsonb), '{allowed_ip}', to_jsonb(target_ip))
  WHERE id = v_user_id;

  RETURN 'Success: Set allowed IP for ' || target_email || ' to ' || target_ip;
END;
$$;



